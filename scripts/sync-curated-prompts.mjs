/**
 * sync-curated-prompts.mjs
 * Exports all curated_prompts from Supabase and writes src/data/curated-prompts.ts.
 * Usage: node scripts/sync-curated-prompts.mjs
 */

import { existsSync, readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";
import { createClient } from "@supabase/supabase-js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const OUT_FILE = resolve(ROOT, "src/data/curated-prompts.ts");

// Load .env then .env.local (both git-ignored; .env.local wins), like the other scripts.
function readEnvFile(path) {
  if (!existsSync(path)) return {};
  return Object.fromEntries(
    readFileSync(path, "utf8")
      .split("\n")
      .filter((l) => l && !l.startsWith("#") && l.includes("="))
      .map((l) => {
        const eq = l.indexOf("=");
        return [
          l.slice(0, eq).trim(),
          l
            .slice(eq + 1)
            .trim()
            .replace(/^["']|["']$/g, ""),
        ];
      }),
  );
}
const env = {
  ...readEnvFile(resolve(ROOT, ".env")),
  ...readEnvFile(resolve(ROOT, ".env.local")),
  ...process.env,
};

const supabase = createClient(
  env.SUPABASE_URL || env.VITE_SUPABASE_URL,
  env.SUPABASE_SERVICE_ROLE_KEY ||
    env.SUPABASE_PUBLISHABLE_KEY ||
    env.VITE_SUPABASE_PUBLISHABLE_KEY,
);

// Fetch all curated prompts. Try the Phase 4 provenance columns first and
// fall back to the Phase 3 column set if that migration has not run.
const BASE_COLUMNS =
  "id, title, category, prompt, why_it_works, source, source_creator, source_url, tags, target_model";
const PROVENANCE_COLUMNS =
  `${BASE_COLUMNS}, slug, source_type, source_notes, status, generation_ready, gallery_ready, ` +
  "needs_reference_images, reference_mode, review_notes, result_count";
let { data, error } = await supabase
  .from("curated_prompts")
  .select(PROVENANCE_COLUMNS)
  .order("category", { ascending: true })
  .order("created_at", { ascending: true });
if (error && /source_type|status|reference_mode|slug/.test(error.message)) {
  console.warn(
    "Provenance columns missing; falling back. Apply supabase/migrations/20260909120000_add_prompt_provenance_to_curated_prompts.sql.",
  );
  ({ data, error } = await supabase
    .from("curated_prompts")
    .select(BASE_COLUMNS)
    .order("category", { ascending: true })
    .order("created_at", { ascending: true }));
}

if (error) {
  console.error("Failed to fetch:", error.message);
  if (/target_model/.test(error.message)) {
    console.error(
      "The target_model column is missing. Apply supabase/migrations/20260908120000_add_target_model_to_curated_prompts.sql first.",
    );
  }
  process.exit(1);
}

// Model versioning: the original collection is gpt-image-2; future Images 2.5
// prompts carry gpt-image-2.5. Rows without a value read as the legacy collection.
const TARGET_MODELS = new Set(["gpt-image-2", "gpt-image-2.5"]);
const targetModelOf = (p) => (TARGET_MODELS.has(p.target_model) ? p.target_model : "gpt-image-2");
const byModel = new Map();
for (const p of data) byModel.set(targetModelOf(p), (byModel.get(targetModelOf(p)) || 0) + 1);

// The TS file is the legacy GPT Image 2 collection only, kept byte-for-byte
// (tests/unit/library-images-2-5-staged.test.ts guards this). Images 2.5 rows
// are served from Supabase; their staged/promotion record is
// src/data/images-2-5-staged.ts plus supabase/insert-images-2-5-batch*-staged.sql.
const skipped = data.filter((p) => targetModelOf(p) !== "gpt-image-2").length;
data = data.filter((p) => targetModelOf(p) === "gpt-image-2");
if (skipped)
  console.log(`Skipped ${skipped} Images 2.5 rows (served from Supabase, not the TS file).`);

// Group by category for organized output
const byCategory = new Map();
for (const p of data) {
  const cat = p.category || "Cinematic";
  if (!byCategory.has(cat)) byCategory.set(cat, []);
  byCategory.get(cat).push(p);
}

// Escape backticks and backslashes for template literal safety
function escapeForTS(str) {
  if (!str) return str;
  return str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$/g, "\\$");
}

// Build the TypeScript file
let ts = `/**
 * ${data.length} curated prompts, synced from Supabase.
 * Collections by target_model: ${[...byModel.entries()].map(([m, n]) => `${m}=${n}`).join(", ")}.
 * Auto-generated by scripts/sync-curated-prompts.mjs — do not edit manually.
 *
 * All categories mapped to Depikt's existing 10:
 *   Posters, Infographics, UI Mockups, Social Posts, Cinematic, Storyboards,
 *   Interior/Food/Fashion, Visual Summaries, Image Edits, Open-Ended Creative
 */

export type CuratedPrompt = {
  id: string;
  title: string;
  category: string;
  prompt: string;
  why_it_works?: string;
  source: 'curated';
  source_creator?: string;
  source_url?: string;
  tags: string[];
  /** Image model the prompt was written for: 'gpt-image-2' (original collection) or 'gpt-image-2.5'. */
  target_model: 'gpt-image-2' | 'gpt-image-2.5';
};

export const curatedPrompts: CuratedPrompt[] = [\n`;

const categoryOrder = [
  "Cinematic",
  "Posters",
  "Infographics",
  "UI Mockups",
  "Social Posts",
  "Storyboards",
  "Interior/Food/Fashion",
  "Visual Summaries",
  "Image Edits",
  "Open-Ended Creative",
];

for (const cat of categoryOrder) {
  const prompts = byCategory.get(cat);
  if (!prompts || prompts.length === 0) continue;

  ts += `  // ============================================================\n`;
  ts += `  // ${cat.toUpperCase()} (${prompts.length})\n`;
  ts += `  // ============================================================\n`;

  for (const p of prompts) {
    ts += `  {\n`;
    ts += `    id: '${p.id}',\n`;
    ts += `    title: '${escapeForTS(p.title).replace(/'/g, "\\'")}',\n`;
    ts += `    category: '${p.category}',\n`;
    ts += `    prompt: \`${escapeForTS(p.prompt)}\`,\n`;
    if (p.why_it_works) {
      ts += `    why_it_works: \`${escapeForTS(p.why_it_works)}\`,\n`;
    }
    ts += `    source: 'curated',\n`;
    if (p.source_creator) {
      ts += `    source_creator: '${escapeForTS(p.source_creator).replace(/'/g, "\\'")}',\n`;
    }
    if (p.source_url) {
      ts += `    source_url: '${escapeForTS(p.source_url)}',\n`;
    }
    ts += `    tags: [${(p.tags || []).map((t) => `'${escapeForTS(t).replace(/'/g, "\\'")}'`).join(", ")}],\n`;
    ts += `    target_model: '${targetModelOf(p)}',\n`;
    ts += `  },\n`;
  }
}

ts += `];\n`;

writeFileSync(OUT_FILE, ts, "utf8");

// Summary
console.log(`Synced ${data.length} prompts to ${OUT_FILE}`);
for (const [m, n] of byModel) console.log(`  target_model ${m}: ${n}`);
for (const cat of categoryOrder) {
  const count = byCategory.get(cat)?.length || 0;
  console.log(`  ${cat}: ${count}`);
}
